/**
 * Resend email fallback
 * Stack contract: email.provider=resend
 * FR-019: If Twilio delivery fails or mobile is missing, send via Resend
 */

import { Resend } from "resend";
import { logger } from "@/lib/logger";

let _client: Resend | null = null;

function getResend(): Resend {
  if (_client) return _client;
  const apiKey = process.env.RESEND_API_KEY;
  if (!apiKey) throw new Error("RESEND_API_KEY not configured");
  _client = new Resend(apiKey);
  return _client;
}

export interface EmailResult {
  id: string;
}

/**
 * Send a quote email fallback via Resend.
 * Called when: (a) customer mobile is missing, (b) Twilio delivery failed.
 */
export async function sendQuoteEmail(
  to: string,
  params: {
    customerName: string;
    tradeName: string;
    address: string;
    quoteLink: string;
    totalAud: string;
  }
): Promise<EmailResult> {
  const resend = getResend();

  const subject = `Quote from ${params.tradeName} for ${params.address.split(",")[0]}`;

  const html = `
<!DOCTYPE html>
<html>
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"></head>
<body style="font-family: sans-serif; max-width: 600px; margin: 0 auto; padding: 20px;">
  <h2 style="color: #1a1a1a;">Your Quote from ${htmlEscape(params.tradeName)}</h2>
  <p>Hi ${htmlEscape(params.customerName.split(" ")[0] ?? params.customerName)},</p>
  <p>${htmlEscape(params.tradeName)} has sent you a quote for work at <strong>${htmlEscape(params.address)}</strong>.</p>
  <p><strong>Total: ${htmlEscape(params.totalAud)}</strong> (inc. GST)</p>
  <p style="margin: 24px 0;">
    <a href="${htmlEscape(params.quoteLink)}"
       style="background: #2563eb; color: white; padding: 12px 24px; border-radius: 6px; text-decoration: none; display: inline-block;">
      View &amp; Accept Quote
    </a>
  </p>
  <p style="color: #666; font-size: 14px;">This quote includes the NSW contractor licence number and statutory warranty wording as required by NSW Fair Trading.</p>
  <hr style="border: none; border-top: 1px solid #e5e7eb; margin: 24px 0;">
  <p style="color: #9ca3af; font-size: 12px;">
    This quote was generated by QuotingAgent. If you have questions, reply to this email or contact ${htmlEscape(params.tradeName)} directly.
  </p>
</body>
</html>
`.trim();

  const { data, error } = await resend.emails.send({
    from: process.env.RESEND_FROM_EMAIL ?? "quotes@quotingagent.com.au",
    to,
    subject,
    html,
  });

  if (error || !data) {
    logger.error({ err: error, to: "[redacted]" }, "resend.email.send_error");
    throw new Error(`Resend send failed: ${error?.message ?? "unknown"}`);
  }

  logger.info({ emailId: data.id }, "resend.email.sent");
  return { id: data.id };
}

function htmlEscape(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}
